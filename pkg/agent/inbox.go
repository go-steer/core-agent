// inboxMessage pairs an inbox message with the prompt_id assigned at
// push time. The prompt_id is the correlation handle threaded through
// the SSE event-stream protocol's `inbox` event (queued / dequeued)
// so an operator-typed prompt can be linked to its downstream
// turn-complete or turn-error. Internal-only — public DrainInbox()
// keeps the legacy []string shape.
//
// caller is the per-message turn originator stamped at Inject /
// InjectAs time. Zero value (Identity == "") means the message
// arrived without an attached identity (legacy Inject path,
// single-user deployments). When the agent loop drains a batch with
// mixed callers, the LAST message's caller becomes the turn
// originator per docs/multi-session-design.md (the turn answers the
// most recent ask).
//
// spanCtx is the OpenTelemetry span context that was active on the
// injecting call's context, captured at InjectAsContext time. It is
// the ONLY thing that survives the inject handler's span: the handler
// returns as soon as the message is queued, so a turn that answers the
// inject minutes later can't be a child of it. Instead the turn span
// carries one LINK per drained inject that had a valid span context
// (see turnspan.go). Zero value (invalid SpanContext) means the inject
// arrived with no trace context — CLI, tests, out-of-band callers, or
// tracing simply switched off — and contributes no link.
//
// quiet marks a message queued by QueueAsContext (POST /inject with
// {"wake": false}, #698): filed for the next turn, whenever that turn
// happens, without preempting the one running or piercing a sleep. It
// is remembered per message rather than being purely a property of the
// push because two later decisions depend on it — see push (no
// InboxArrived signal) and HasPendingOperatorInput (a message that
// won't drive a turn must not make auto-continue stand down waiting
// for one).
type inboxMessage struct {
	id      string
	text    string
	caller  auth.Caller
	spanCtx trace.SpanContext
	quiet   bool
}

// newPromptID returns a new prompt_id. UUID v7 is sortable by
// creation time, so debugging traces stay ordered without a
// separate timestamp.
func newPromptID() string {
	id, err := uuid.NewV7()
	if err != nil {
		// Fallback to V4 — V7 only fails when the OS clock is
		// unrecoverably broken, which we can't do anything useful
		// about here. A V4 still uniquely identifies the prompt;
		// debugging just loses the time-ordering property.
		return uuid.NewString()
	}
	return id.String()
}

// inbox is the per-Agent queue of external messages injected via
// Agent.Inject. Drained pre-turn by Agent.Run and prepended to the
// prompt the model sees on its next turn, sibling to the v1.2.0
// background-agent alert block.
//
// External meaning: not generated by the agent itself or its
// subagents (those are alerts on BackgroundAgentManager). Inbox is
// for harness / orchestrator / external-event input that arrives
// asynchronously while the agent is working.
type inbox struct {
	mu       sync.Mutex
	messages []inboxMessage
	notify   chan struct{} // 1-buffer signal; non-blocking send on append
	closed   bool
}

// newInbox returns an empty inbox ready to accept Inject calls.
func newInbox() *inbox {
	return &inbox{
		notify: make(chan struct{}, 1),
	}
}

// defaultInboxCap is the soft cap on queued messages before
// drop-oldest kicks in. Matches the v1.2.0 alert channel default
// (256) so consumers see consistent backpressure semantics across
// the two surfaces.
const defaultInboxCap = 256

// ErrInboxClosed is returned by Agent.Inject when the agent's inbox
// has been closed (typically because the agent has been shut down
// via its run context cancelling). Callers that publish messages on
// an unrelated lifecycle (e.g. a stdin scanner) should treat this as
// "stop publishing."
var ErrInboxClosed = errors.New("agent: inbox closed")

// push appends msg to the queue with drop-oldest backpressure when
// the queue grows past defaultInboxCap, and fires notify so a
// waiting Agent.InboxArrived consumer wakes up. Returns the
// prompt_id assigned to the new message so the caller can emit a
// downstream `inbox` event carrying the correlation handle.
//
// caller is the originator stamped on the message; zero value means
// "no attached identity" (legacy Inject path). spanCtx is the trace
// context of the injecting call, zero (invalid) when the inject
// carried none.
//
// quiet suppresses the notify signal. InboxArrived is the harness-side
// analogue of the wake signal — the documented pattern is to start a
// turn when it fires — so a message that deliberately does not wake the
// agent must not drive one through the side door either. It is still
// appended, still counted, and still drained by the next turn.
func (q *inbox) push(msg string, caller auth.Caller, spanCtx trace.SpanContext, quiet bool) (string, error) {
	id := newPromptID()
	q.mu.Lock()
	if q.closed {
		q.mu.Unlock()
		return "", ErrInboxClosed
	}
	q.messages = append(q.messages, inboxMessage{id: id, text: msg, caller: caller, spanCtx: spanCtx, quiet: quiet})
	if len(q.messages) > defaultInboxCap {
		// Drop oldest with a logged warning so a stuck producer
		// can't deadlock the agent.
		dropped := q.messages[0]
		q.messages = q.messages[1:]
		log.Printf("agent: inbox cap exceeded, dropped oldest message (id=%s head=%q)",
			dropped.id, truncateForLog(dropped.text))
	}
	q.mu.Unlock()
	if quiet {
		return id, nil
	}
	// Non-blocking signal. If a notification is already buffered
	// (consumer hasn't drained yet), drop the redundant signal.
	select {
	case q.notify <- struct{}{}:
	default:
	}
	return id, nil
}

// drain returns all currently-queued messages (with their prompt_ids)
// in arrival order and clears the queue. Safe to call concurrently
// with push. Internal-only — the public Agent.DrainInbox() wraps this
// in drainText for the legacy []string return shape.
func (q *inbox) drain() []inboxMessage {
	q.mu.Lock()
	defer q.mu.Unlock()
	if len(q.messages) == 0 {
		return nil
	}
	out := q.messages
	q.messages = nil
	return out
}

// arrived returns the notification channel a consumer can select on
// to wait for a new push. The channel is shared across consumers;
// only one goroutine should select on it at a time.
func (q *inbox) arrived() <-chan struct{} { return q.notify }

// close marks the inbox closed so subsequent push calls error. Safe
// to call multiple times.
func (q *inbox) close() {
	q.mu.Lock()
	q.closed = true
	q.mu.Unlock()
}

// truncateForLog produces a short single-line preview of msg for
// inclusion in log lines.
func truncateForLog(msg string) string {
	const max = 60
	msg = strings.ReplaceAll(msg, "\n", " ")
	if len(msg) <= max {
		return msg
	}
	return msg[:max-3] + "..."
}

// prependInboxMessages renders queued inbox messages as a stable,
// greppable block and prepends them to prompt. Empty queue returns
// prompt unchanged. Format mirrors the BackgroundAgentManager alert
// block from v1.2.0 so consumer tooling can find both boundaries
// with the same approach.
//
// bundleIsTheTurn says whether the operator supplied any text of their
// own for this turn, and it selects the framing (#697). It is NOT the
// same question as "is prompt empty": Agent.Run prepends background
// alerts before this call, so a wake-driven turn carrying a subagent
// report arrives here with a non-empty prompt and still has nobody
// asking anything. Callers pass the operator's raw text, before any
// prepends.
//
//   - Operator text present: the inbox is side context and the
//     operator's own prompt is the ask, so the bare list is right —
//     bundle guidance ("respond once to the bundle") would compete
//     with the thing the operator actually typed.
//   - No operator text (the daemon's Run(ctx, "") after an inject,
//     the REPL's wake-driven turn): the bundle IS the turn, so it gets
//     the same handling guidance the TUI's auto-continue flow has had
//     since #144. Injected machine signals arrive on this path, and
//     without the guidance they were read as N independent asks — the
//     #697 failure, where two corroborating blast-radius alerts about
//     an already-resolved incident drove a 22-call tool loop.
func prependInboxMessages(prompt string, messages []string, bundleIsTheTurn bool) string {
	if len(messages) == 0 {
		return prompt
	}
	block := formatInboxForPrompt(messages)
	if bundleIsTheTurn {
		block = formatInboxBundle("[Inbox]", messages)
	}
	if strings.TrimSpace(prompt) == "" {
		// Nothing below, so no separator: a trailing "---" with empty
		// space under it reads as a truncated prompt.
		return block
	}
	return block + "\n\n---\n\n" + prompt
}

// formatInboxForPrompt renders one message per line under an
// "[Inbox]" header. Stable + greppable.
func formatInboxForPrompt(messages []string) string {
	var b strings.Builder
	b.WriteString("[Inbox]\n")
	for i, m := range messages {
		if i > 0 {
			b.WriteByte('\n')
		}
		b.WriteString("- ")
		b.WriteString(m)
	}
	return b.String()
}

// inboxHandlingGuidance is the branch list appended to a queued bundle
// that is itself the turn. Shared verbatim by every such surface —
// keeping one copy is the point, since the two that existed drifted
// (#697: the TUI's auto-continue flow had the v2 branches, the daemon's
// inject path had none, and machine signals only ever arrive on the
// second one).
//
// Iteration history:
//
//   - v1 (PR-α): "If any of these change the current task, adapt your
//     next step. If they're separate requests, use the `todo` tool to
//     capture them and continue what you were doing." Both branches
//     assumed an active task to "continue" — false after
//     mark_task_done. A bundle of similar asks got handled as N
//     separate tasks (issue #144's read_file loop pattern).
//   - v2 (#144): explicit branches for (a) variants-of-the-same-ask
//     dedup, (b) mid-task adjustments, (c) separate asks during an
//     active task, (d) post-completion bundles.
//   - v3 (#697): reworded off "notes"/"operator" and onto "messages",
//     because the surface that needed this most is machine signals,
//     which are neither notes nor asks; added the corroboration branch,
//     which is the specific shape a watcher produces — a second signal
//     about something already handled, which reads as new work unless
//     the model is told otherwise.
const inboxHandlingGuidance = "How to handle the bundle:\n" +
	"- Variants of the same ask or signal → treat as ONE; don't re-do work per message.\n" +
	"- Corroborating detail on something you already handled → acknowledge it and move on; do not re-open the work.\n" +
	"- Mid-task adjustments → adapt your next step.\n" +
	"- Separate asks during an active task → capture with `todo`, continue what you were doing.\n" +
	"- After a completed task (the latest message is a checkpoint summary) → treat the bundle as the next request and respond once."

// formatInboxBundle renders messages under header as a bullet list
// followed by inboxHandlingGuidance. Returns "" for an empty bundle.
// The header is the caller's because it is the one part that legitimately
// differs by surface: "[Inbox]" is the stable, greppable, documented
// name of the daemon block, while the TUI's auto-continue turn says
// where its notes came from.
func formatInboxBundle(header string, messages []string) string {
	if len(messages) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteByte('\n')
	for _, m := range messages {
		b.WriteString("- ")
		b.WriteString(m)
		b.WriteByte('\n')
	}
	b.WriteByte('\n')
	b.WriteString(inboxHandlingGuidance)
	return b.String()
}

// FormatAutoContinueInbox renders messages with the system-note
// framing used by the TUI's "auto-continue from queued input"
// flow (see docs/operator-input-design.md). The framing tells the
// model these notes arrived while it was working and gives it the
// explicit branches in inboxHandlingGuidance — most importantly the
// dedup case (operators frequently re-phrase the same ask while
// waiting) and the post-completion case (the prior turn ended with
// mark_task_done, so there's no "current task" to adapt).
//
// Only the header is this flow's own: these notes really are an
// operator's, and saying so is worth a line, whereas the daemon's
// block carries machine signals under the stable "[Inbox]" name.
// Everything below the bullets is shared with the daemon path, so the
// two can no longer drift (#697).
//
// Returns "" when messages is empty (caller should not auto-continue
// in that case).
func FormatAutoContinueInbox(messages []string) string {
	return formatInboxBundle("[Operator notes queued while you were working]", messages)
}

// FormatInterruptSteer frames the instruction an operator typed in
// answer to "what do you want me to do instead?" after interrupting a
// turn. Sibling of FormatAutoContinueInbox, and deliberately blunter:
// auto-continue is guessing that the model should carry on, whereas
// here a human explicitly stopped the model and said something. The
// last line exists because the default failure mode of a resumed model
// is to quietly go back to what it was doing and mention the operator's
// note in passing.
//
// Returns "" for empty text so callers can fall back to
// FormatInterruptContinue.
func FormatInterruptSteer(text string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return ""
	}
	var b strings.Builder
	b.WriteString("[The operator interrupted you]\n")
	b.WriteString("You were stopped mid-task by a human operator, who then said:\n")
	b.WriteString("- ")
	b.WriteString(text)
	b.WriteString("\n\n")
	b.WriteString("Follow the operator's instruction. If it supersedes what you were doing, drop the old approach; if it adjusts it, adapt your next step. Do not silently resume the interrupted work.")
	return b.String()
}

// FormatInterruptContinue frames a resume that carries no new
// instruction — the operator stopped the model, looked, and said carry
// on. Distinct from AutoContinueNoteFor because the interruption here
// was deliberate and human, so the model shouldn't treat the stop
// itself as a signal that something went wrong.
//
// The re-check line is the load-bearing one: tail repair (#537) patches
// a dangling functionCall into a well-formed history, but the real-world
// EFFECT of a cancelled bash or write_file is genuinely unknown, and a
// model that assumes completion will happily build on a half-applied
// change.
func FormatInterruptContinue() string {
	return "[The operator interrupted you, then told you to carry on]\n" +
		"A human operator stopped you mid-task and has now resumed you with no new instructions. " +
		"Pick up where you left off.\n\n" +
		"Your last tool call may have been cancelled part-way through — re-check its state before assuming it completed."
}

// Inject queues message on the agent's inbox. The next call to
// Agent.Run will drain pending messages, format them as an "[Inbox]"
// block, and prepend the block to the prompt the model sees.
//
// Inject is safe to call concurrently from any goroutine — typical
// usage is a harness goroutine reading from stdin, an HTTP handler,
// or an orchestrator's gRPC stream. Drop-oldest backpressure kicks
// in when the queue exceeds the soft cap (256) so a stuck consumer
// can't deadlock the agent.
//
// Emits an `inbox`/queued event on the attach event stream (if one
// is wired) with the assigned prompt_id, so SSE consumers can
// surface the queued state to operators. The same prompt_id flows
// out as the `inbox`/dequeued event when the inbox is drained
// inside Run.
//
// Returns ErrInboxClosed once the agent has been shut down; callers
// publishing on an unrelated lifecycle should treat that as "stop."
//
// Inject queues without an originator identity. Callers that have a
// per-request auth.Caller (typically attach handlers in a
// multi-session deployment) should use InjectAs instead — the caller
// is threaded into the turn context so the eventlog metadata sidecar
// and per-caller MCP path see who triggered the turn.
//
// Inject carries no trace context. Callers on an HTTP request path
// (the attach /inject and /wake handlers, an orchestrator's RPC
// server) should use InjectAsContext so the turn that answers the
// inject can be linked back to the injecting span.
func (a *Agent) Inject(message string) error {
	return a.InjectAs(message, auth.Caller{})
}

// InjectAs is Inject with a per-message originator identity. The
// caller is stored on the queued message and used as the turn
// originator when the inbox drains: the agent loop wraps the turn
// context with auth.WithCaller(caller) so eventlog metadata, MCP
// outbound context, and other caller-aware substrates see the
// identity that triggered the turn.
//
// Zero-value caller (Identity == "") is equivalent to Inject — no
// identity is threaded.
//
// When multiple injects queue between turns, the LAST message's
// caller wins as the turn originator (per
// docs/multi-session-design.md "the turn answers the most recent
// ask"). Same prompt_id correlation, same SSE events as Inject.
//
// InjectAs carries no trace context; see InjectAsContext.
func (a *Agent) InjectAs(message string, caller auth.Caller) error {
	return a.InjectAsContext(context.Background(), message, caller)
}

// InjectAsContext is InjectAs plus the injecting call's context, so
// the queued message remembers the OpenTelemetry span that produced
// it. Everything else is identical — same queue, same prompt_id, same
// SSE events, same last-caller-wins originator rule.
//
// ctx is used ONLY to read the active span context. It is deliberately
// not stored, not used for cancellation, and not consulted for the
// caller identity (pass that explicitly): an inbox message outlives
// the request that queued it by design, so keeping the request's
// context alive on the queue would be a lifetime bug.
//
// Why a link and not a parent: the injecting request returns as soon
// as the message is queued, so its span has already ended by the time
// a turn drains the inbox — and one turn can drain SEVERAL injects, so
// there is no single parent to pick. The agent loop therefore attaches
// one span LINK per drained inject that carried a valid span context
// to the turn span it starts (see turnspan.go). Injects with no trace
// context are a clean no-op.
func (a *Agent) InjectAsContext(ctx context.Context, message string, caller auth.Caller) error {
	_, err := a.InjectAsContextWithID(ctx, message, caller)
	return err
}

// InjectAsContextWithID is InjectAsContext returning the prompt_id it
// assigned to the queued message — the same id that goes out on the
// `inbox`/queued event, comes back on `inbox`/dequeued when a turn
// drains it, and names the turn on `turn-complete`.
//
// It exists because the id was being computed and thrown away: an
// attach client that puts a chat thread in front of a session has no
// other way to key state on the turn its message will produce.
// `turn-complete.prompt_id` names it, but only at the end, and by then
// the client needed to have known since the start; the `inbox` events
// carry it but have no `seq`, so a counter driven off them
// desynchronises across exactly the reconnect it most needs to survive;
// and correlating "the queued event that just fired" with "the inject
// I just sent" holds right up until two goroutines inject on one
// session, which is the case that needs it (#840).
//
// A sibling rather than a changed signature: pkg/agent is inside the
// stability promise, and InjectAsContext returning (string, error)
// would be a source break for every out-of-tree caller.
//
// The id is NOT one-to-one with a turn, and callers must not treat it
// as one. The inbox coalesces — several messages queued between turns
// drain into a single "[Inbox]" block and run as one turn (see
// docs/multi-session-design.md, "the turn answers the most recent
// ask") — so N injects can share one turn, and `turn-complete` names
// only one of the ids. What the id buys is the ability to SEE that
// fan-in and collapse client state accordingly, which is not possible
// without it.
func (a *Agent) InjectAsContextWithID(ctx context.Context, message string, caller auth.Caller) (string, error) {
	return a.injectAs(ctx, message, caller, injectMode{releaseHold: true, wake: true})
}

// QueueAsContext files a message for the agent to read on its next
// turn WITHOUT causing that turn (#698). It is InjectAsContext minus
// the two things that make an inject preemptive: it does not fire the
// wake signal, and it does not open a pause gate an operator closed.
// Everything else is identical — same queue, same prompt_id, same
// `inbox`/queued event, same caller and trace-context handling, same
// drain path, same last-caller-wins originator rule.
//
// This is the "file this away" primitive behind POST /inject with
// {"wake": false}. Its use case is a machine producer — an alert
// watcher, a monitoring hook — that has corroborating context worth
// having but no claim on the agent's attention right now. Before it,
// every such message drove its own turn: two watcher signals two
// minutes apart meant two wakes, the second landing while the agent
// was still working the first. Queued, they drain together as one
// block on whatever turn happens next.
//
// It makes NO promptness guarantee, and callers must treat that
// literally. The message is drained by the next turn, but nothing here
// causes a next turn: an autonomous loop reaches one on its own sleep
// timer, an operator-driven session reaches one when the operator says
// something, and a session that is parked reaches one when it is
// resumed. If the message needs to be acted on, inject it normally.
//
// Zero-value caller and the ctx rules are exactly InjectAsContext's;
// see there.
func (a *Agent) QueueAsContext(ctx context.Context, message string, caller auth.Caller) error {
	_, err := a.QueueAsContextWithID(ctx, message, caller)
	return err
}

// QueueAsContextWithID is QueueAsContext returning the prompt_id it
// assigned — the deferred sibling of InjectAsContextWithID, and see
// there for why the id is worth having and why it is not a turn
// identity.
//
// Both deliveries report an id because the client-side problem is the
// same on either: a deferred message still drains into a turn, still
// produces an `inbox`/queued frame, and still leaves a gateway with
// nothing to key on. Reporting the id on only the waking path would
// make the response shape depend on a flag in the request, which is
// the kind of conditional field clients read wrong.
func (a *Agent) QueueAsContextWithID(ctx context.Context, message string, caller auth.Caller) (string, error) {
	return a.injectAs(ctx, message, caller, injectMode{})
}

// injectMode carries the two axes on which the queue-and-notify core
// varies. Both default to the quiet, non-preemptive setting so a
// zero value is the QueueAsContext behavior; the ordinary inject
// path opts into both.
type injectMode struct {
	// releaseHold opens a pause gate the message should un-park.
	// False for callers that open it themselves afterwards —
	// ResumeWith needs the message on the queue before the gate
	// opens, so the turn the resume releases can't start ahead of
	// the instruction that was meant to shape it — and for
	// QueueAsContext, where the whole point is not to un-park.
	releaseHold bool
	// wake fires the wake signal so the message preempts a sleep.
	// False for QueueAsContext (#698).
	wake bool
}

// injectAs is the queue-and-notify core. It returns the prompt_id the
// inbox assigned, which the *WithID entry points hand back to callers
// that need to key state on the turn this message will land in (#840).
//
// ctx supplies the trace context stamped on the queued message.
// Reading it is a plain context-value lookup that returns a value
// type, so the capture allocates nothing and costs nothing extra when
// tracing is off (the returned SpanContext is simply invalid).
func (a *Agent) injectAs(ctx context.Context, message string, caller auth.Caller, mode injectMode) (string, error) {
	if a == nil {
		return "", errors.New("agent: nil receiver")
	}
	if a.inbox == nil {
		// Defensive: callers should always go through agent.New
		// which constructs a non-nil inbox, but if a consumer
		// hand-constructed an Agent struct (tests in this package
		// do, for example) we don't want to panic.
		return "", errors.New("agent: inbox not initialised (construct via agent.New)")
	}
	id, err := a.inbox.push(message, caller, trace.SpanContextFromContext(ctx), !mode.wake)
	if err != nil {
		return "", err
	}
	a.Emit(attach.EventInbox, attach.InboxEvent{
		State:    attach.InboxStateQueued,
		PromptID: id,
		QueuedAt: time.Now().UTC(),
	})
	// Operator input releases a pause hold. Injecting while parked is
	// how an operator answers the "what do you want me to do instead?"
	// prompt, so it has to open the gate — otherwise the message sits
	// in an inbox nothing will drain. This is also what keeps the
	// long-standing API pattern (POST /interrupt then POST /inject)
	// behaviorally identical now that interrupt holds by default.
	//
	// Auto-continue's own notes are excluded: a timer-driven "carry on
	// with the task" must never un-park a loop a human deliberately
	// parked. That's the pause-side sibling of the #624 stand-down
	// (see HasPendingOperatorInput), and pkg/compose additionally has
	// auto-continue skip the inject entirely while paused.
	if mode.releaseHold && caller.Identity != AutoContinueOriginator {
		a.Resume()
	}
	// Operator input should also pierce any active sleep — the
	// scheduler selects on WakeRequested() alongside its sleep
	// timer, so this lands as an immediate wake.
	//
	// Fires the signal directly rather than through RequestWake so no
	// `wake` event goes out (#802): this inject already published an
	// `inbox`/queued event a few lines up, and a second frame saying
	// "something wants your attention" about the operator's own typed
	// prompt is noise on every single message. RequestWake is for the
	// wakes nothing else on the wire accounts for.
	//
	// Skipped entirely by QueueAsContext: not waking IS the feature
	// there. The `inbox`/queued event above still goes out, so a
	// deferred message is visible to attached operators the moment it
	// lands — it just doesn't interrupt anything.
	if mode.wake {
		a.wake.fire()
	}
	return id, nil
}

// DrainInbox pulls every currently-queued message off the inbox and
// returns them in arrival order. The queue is emptied as a side
// effect — repeat calls return nil until new messages arrive.
//
// Exposed so harnesses that want to format inbox messages
// differently from the built-in `[Inbox]` block (e.g. the TUI's
// auto-continue flow uses FormatAutoContinueInbox to add system-note
// framing) can pull the messages themselves and pass the formatted
// result to Run as a regular prompt. Run's internal drain then
// finds an empty inbox and is a no-op, so there's no
// double-injection.
//
// Returns nil when no agent or no inbox is wired — both are
// defensive cases for hand-constructed Agent structs in tests.
//
// Emits an `inbox`/dequeued event for each drained message with the
// message's prompt_id, so SSE consumers can correlate the dequeue
// with the earlier queued event.
//
// Callers that need the per-message originator identity (multi-session
// turn threading) should use drainInboxFull instead (internal). The
// public DrainInbox shape is preserved for external harnesses that
// only care about the text payloads.
func (a *Agent) DrainInbox() []string {
	return a.drainInboxFull().texts
}

// inboxDrain is one pre-turn inbox drain, as Agent.Run consumes it.
// A struct rather than a widening tuple: the drain already carries
// three independent facts about the batch and the turn-span links
// made it four.
type inboxDrain struct {
	// texts are the drained message bodies in arrival order.
	texts []string
	// originator is the last non-empty caller in the batch — the
	// turn's originator per docs/multi-session-design.md ("the turn
	// answers the most recent ask"). Zero when nothing carried an
	// identity. Deferred messages (#698) yield to waking ones; see
	// drainInboxFull.
	originator auth.Caller
	// links are the span links for the turn span, at most
	// maxTurnSpanLinks of them (see inboxTraceLinks).
	links []trace.Link
	// linkedInjects is how many drained messages carried a valid
	// trace context, BEFORE the link cap is applied. Recorded as a
	// span attribute so a capped batch is still countable.
	linkedInjects int
}

// drainInboxFull is the internal drain variant used by Agent.Run to
// pick up the turn originator alongside the message texts. Returns
// the last non-empty caller in the drained batch (per
// docs/multi-session-design.md, "the turn answers the most recent
// ask"). Zero originator when no message carried an identity — the
// caller then runs the turn without wrapping the context.
//
// Deferred messages (#698) lose to waking ones regardless of arrival
// order, because they are not asks. Without that, a watcher quietly
// filing context in the seconds between an operator's inject and the
// turn it caused would take over as originator — and the originator is
// what stamps eventlog attribution and picks the per-caller MCP
// credentials, so the operator's turn would run as the watcher. A
// batch that is entirely deferred still attributes to its last
// identity: there, the machine producer IS the only ask.
//
// Also returns the turn-span links derived from the batch's captured
// trace contexts (see inboxTraceLinks). Empty for a batch where
// nothing was traced.
//
// Emits the same `inbox`/dequeued events DrainInbox emits, so the
// public-method side effect is preserved.
func (a *Agent) drainInboxFull() inboxDrain {
	if a == nil || a.inbox == nil {
		return inboxDrain{}
	}
	msgs := a.inbox.drain()
	if len(msgs) == 0 {
		return inboxDrain{}
	}
	d := inboxDrain{texts: make([]string, len(msgs))}
	var deferredCaller auth.Caller
	for i, m := range msgs {
		a.Emit(attach.EventInbox, attach.InboxEvent{
			State:    attach.InboxStateDequeued,
			PromptID: m.id,
		})
		d.texts[i] = m.text
		switch {
		case m.caller.Identity == "":
		case m.quiet:
			deferredCaller = m.caller // only used if nothing woke
		default:
			d.originator = m.caller // last-write-wins
		}
	}
	if d.originator.Identity == "" {
		d.originator = deferredCaller
	}
	d.links, d.linkedInjects = inboxTraceLinks(msgs)
	return d
}

// PendingInboxCount peeks at the inbox without draining it. Useful
// for UI surfaces (TUI queue panel) that need to render the current
// queue length without claiming the messages.
//
// Returns 0 for nil agent / inbox.
func (a *Agent) PendingInboxCount() int {
	if a == nil || a.inbox == nil {
		return 0
	}
	a.inbox.mu.Lock()
	defer a.inbox.mu.Unlock()
	return len(a.inbox.messages)
}

// HasPendingOperatorInput reports whether the inbox holds a queued
// message from someone OTHER than auto-continue itself — real
// operator/external input waiting to drive the next turn. Auto-continue
// consults this to STAND DOWN (#624): if an operator has already queued
// input (e.g. `stop`) while a turn was interrupted, that input must
// drive the next turn on its own — injecting a "continue the task" note
// into the same drained batch lets the note outrank the operator's stop
// (the #624 race). Messages injected by auto-continue itself
// (AutoContinueOriginator) are excluded so it never sees its own note as
// operator input. Zero-identity messages (legacy Inject / single-user)
// DO count — they are operator input without an attached identity.
//
// Messages queued by QueueAsContext (#698) are excluded too, for the
// same reason auto-continue consults this at all: the stand-down is
// worth it only because the queued input is ITSELF about to drive a
// turn. A deferred message explicitly is not — standing down for one
// would leave an interrupted session with nothing to re-drive it and
// the deferred context undrained, which is the opposite of both
// features' intent. Auto-continue proceeds, and its turn drains the
// deferred message alongside its own note, which is exactly the
// batching {"wake": false} exists to get.
//
// Returns false for nil agent / inbox.
func (a *Agent) HasPendingOperatorInput() bool {
	if a == nil || a.inbox == nil {
		return false
	}
	a.inbox.mu.Lock()
	defer a.inbox.mu.Unlock()
	for _, m := range a.inbox.messages {
		if m.quiet {
			continue
		}
		if m.caller.Identity != AutoContinueOriginator {
			return true
		}
	}
	return false
}

// InboxArrived returns a channel that fires when a new message has
// been injected. The harness can use this to decide when to start
// the next turn instead of polling — typical pattern:
//
//	for {
//	    select {
//	    case <-ctx.Done():
//	        return
//	    case <-ag.InboxArrived():
//	        runOneTurn("continue") // inbox prepended automatically
//	    }
//	}
//
// The channel has a 1-buffer signal-style semantics: multiple pushes
// between consumer wake-ups coalesce into one notification (the
// consumer drains the queue and sees them all).
func (a *Agent) InboxArrived() <-chan struct{} {
	if a == nil || a.inbox == nil {
		return nil
	}
	return a.inbox.arrived()
}

// CloseInbox marks the agent's inbox closed so every subsequent
// Inject / InjectAs fails with ErrInboxClosed instead of queuing into
// a mailbox no live turn will ever drain. The wake-driven surfaces
// (runner.WakeLoop) call this when their loop exits — both daemon
// shutdown and per-session eviction cancel that loop's context — so a
// post-death inject that raced past handler-level gating fails loudly
// at the source rather than being acknowledged and silently lost
// (#566). Idempotent and nil-safe.
func (a *Agent) CloseInbox() {
	if a == nil || a.inbox == nil {
		return
	}
	a.inbox.close()
}
